const {app,BrowserWindow}=require('electron');
const {mkdtempSync,writeFileSync}=require('node:fs');
const {tmpdir}=require('node:os');
const path=require('node:path'),assert=require('node:assert/strict');
app.setPath('userData',mkdtempSync(path.join(tmpdir(),'ga-names-')));
const deadline=setTimeout(()=>app.exit(1),150000);
app.whenReady().then(async()=>{
 const win=new BrowserWindow({show:false,width:1440,height:900,webPreferences:{offscreen:true}});
 win.webContents.setBackgroundThrottling(false);
 const run=code=>win.webContents.executeJavaScript(code,true);
 const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
 const wait=async code=>{for(let i=0;i<700;i++){if(await run(code))return;await pause(30)}throw Error('Timeout '+code)};
 const shot=async name=>{await pause(100);writeFileSync(path.resolve(`dist/names-${name}.png`),(await win.webContents.capturePage()).toPNG())};
 const errors=[];win.webContents.on('console-message',detail=>{if(detail.level==='error')errors.push(detail.message)});
 await win.loadFile(path.resolve('dist/renderer/index.html'));
 await wait(`Boolean(document.querySelector('.welcome input[name=name]'))`);
 await shot('welcome');
 await run(`document.querySelector('input[name=seed]').value='ui-regression';document.querySelector('input[name=name]').value='雨音 / Rain';document.querySelector('.welcome form').requestSubmit()`);
 await wait(`document.querySelector('.town-model')?.dataset.ready==='true'&&!document.querySelector('.scene-transition')`);
 const initial=await run(`localStorage.getItem('greeting-adventurer.save.v1')`);
 await run(`document.querySelector('[data-building-tab=tavern]').click()`);
 await wait(`Boolean(document.querySelector('.facility-reception'))`);
 const chinese=await run(`document.querySelector('.window-surface').innerText`);
 assert(chinese.includes('杜寬'));
 await shot('tavern-zh');
 await run(`document.querySelector('.window-back button').click();document.querySelector('.save-tools').open=true;const select=document.querySelector('[data-toolbar] select');select.value='en';select.dispatchEvent(new Event('change',{bubbles:true}))`);
 await run(`document.querySelector('[data-building-tab=tavern]').click()`);
 await wait(`document.querySelector('.facility-reception')?.getAttribute('aria-label')==='Du Kuan'`);
 const english=await run(`document.querySelector('.window-surface').innerText`);
 assert(!/[\u3400-\u9fff]/.test(english),english);
 assert.notEqual(english,chinese);
 assert.equal(await run(`localStorage.getItem('greeting-adventurer.save.v1')`),initial,'locale and facility changes must not mutate save');
 await shot('tavern-en');
 await run(`document.querySelector('.window-back button').click();document.querySelector('[data-player-menu]').click()`);
 await wait(`document.querySelector('.window-surface')?.innerText.includes('雨音 / Rain')`);
 await run(`document.querySelector('[data-menu-tab=formation]').click()`);
 await wait(`document.querySelector('.formation-members')?.innerText.includes('雨音 / Rain')`);
 await shot('formation-en');
 win.setSize(800,600);
 await pause(250);
 assert(await run(`(()=>{const surface=document.querySelector('.window-surface').getBoundingClientRect();return surface.left>=-1&&surface.right<=innerWidth+1})()`));
 await shot('formation-small');
 await run(`localStorage.clear()`);await win.reload();
 await wait(`Boolean(document.querySelector('.welcome input[name=name]'))`);
 await run(`document.querySelector('input[name=name]').value='Rain'.repeat(20);document.querySelector('.welcome form').requestSubmit()`);
 await wait(`document.querySelector('.town-model')?.dataset.ready==='true'&&!document.querySelector('.scene-transition')`);
 await run(`document.querySelector('[data-player-menu]').click()`);
 await wait(`Boolean(document.querySelector('[data-menu-tab=formation]'))`);
 await run(`document.querySelector('[data-menu-tab=formation]').click()`);
 await wait(`Boolean(document.querySelector('.formation-board'))`);
 assert(await run(`(()=>{const board=document.querySelector('.formation-board');return board.scrollWidth<=board.clientWidth+1&&document.querySelector('.formation-board [data-occupied=true]').title==='Rain'.repeat(20)})()`),'80-character names stay within cells and keep their full tooltip');
 await shot('long-name-small');
 assert.deepEqual(errors,[]);
 console.log('NAMING UI PASSED: custom opening name, translated host and tavern names, locale switch without save mutation, formation and 800px layout');
 clearTimeout(deadline);app.exit(0);
}).catch(error=>{console.error(error);clearTimeout(deadline);app.exit(1)});
